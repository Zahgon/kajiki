"""Write pytypedicts.go: the names in the __dict__ of CPython 3.12's builtin classes, which dir() lists.

Run with the reference CPython, from this directory: python3 gen_typedicts.py > pytypedicts.go
"""
import builtins
import sys
import types

classes = [object, type, int, bool, float, complex, str, bytes, bytearray, list, tuple, dict, set, frozenset,
           range, slice, property, classmethod, staticmethod, super, enumerate, zip, map, filter, reversed,
           types.FunctionType, types.BuiltinFunctionType, types.MethodType, types.GeneratorType, types.ModuleType,
           type(None), type(...), type(NotImplemented), type({}.keys()), type({}.values()), type({}.items()),
           type(iter([])), type(iter(())), type(iter('')), type(iter(range(0))), type(iter({})), type(iter(set()))]
classes += [c for c in vars(builtins).values() if isinstance(c, type) and issubclass(c, BaseException)]

print('// Code generated by gen_typedicts.py from CPython %s; DO NOT EDIT.' % sys.version.split()[0])
print()
print('// Copyright 2001 Python Software Foundation.')
print('// SPDX-License-Identifier: PSF-2.0')
print()
print('package py')
print()
print('// typeDictNames lists the names in the __dict__ of each builtin class.')
print('var typeDictNames = map[string][]string{')
seen = set()
for c in classes:
    if c.__name__ in seen:
        continue
    seen.add(c.__name__)
    names = ', '.join('"%s"' % n for n in sorted(c.__dict__))
    print('\t"%s": {%s},' % (c.__name__, names))
print('}')
