"""Write html5.go from html.entities of the running CPython.

Run with the pinned CPython 3.12.15 from this directory, then format the
result: python3 gen.py && gofmt -w html5.go
"""

import html.entities
import platform


def go_quote(s):
    """Return s as a Go interpreted string literal using only ASCII."""
    out = ['"']
    for ch in s:
        c = ord(ch)
        if ch in '"\\':
            out.append('\\' + ch)
        elif 0x20 <= c < 0x7F:
            out.append(ch)
        elif c <= 0xFFFF:
            out.append('\\u%04x' % c)
        else:
            out.append('\\U%08x' % c)
    out.append('"')
    return ''.join(out)


def main():
    table = html.entities.html5
    lines = [
        '// Code generated by gen.py from CPython %s html.entities.html5. DO NOT EDIT.'
        % platform.python_version(),
        '',
        'package entities',
        '',
        '// HTML5 is html.entities.html5: the %d HTML5 named character references,'
        % len(table),
        '// keyed by the name as written after the "&" (with its ";" where the name',
        '// requires one, as in "amp;", and without it for the legacy names that may',
        '// omit it, as in "amp"), mapped to the replacement text.',
        'var HTML5 = map[string]string{',
    ]
    for name in sorted(table):
        lines.append('\t%s: %s,' % (go_quote(name), go_quote(table[name])))
    lines.append('}')
    with open('html5.go', 'w', encoding='ascii', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
