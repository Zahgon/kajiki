#!/usr/bin/env python3
"""Write internal/pyuni/normalize_tables.go: the data of unicodedata.normalize('NFKC').

The full compatibility decompositions (the Hangul syllables, which decompose by arithmetic, left
out), the canonical combining classes and the primary composites are read back from CPython 3.12's
unicodedata, so they follow its Unicode version (15.0.0). Run inside the pinned image from
gold/internal/pyuni, as gen_tables.py is:

    rec/py.sh gold/internal/pyuni python3 gen/gen_normalize.py normalize_tables.go
"""
import sys
import unicodedata

ALL = range(0x110000)
HANGUL = range(0xAC00, 0xAC00 + 11172)


def go_char(ch):
    if 0x20 <= ord(ch) < 0x7F and ch not in '"\\':
        return ch
    if ord(ch) > 0xFFFF:
        return "\\U%08x" % ord(ch)
    return "\\u%04x" % ord(ch)


def go_string(s):
    return '"' + "".join(go_char(ch) for ch in s) + '"'


def emit_items(out, items):
    line = "\t"
    for item in items:
        if len(line) + len(item) > 100:
            out.append(line.rstrip())
            line = "\t"
        line += item + " "
    if line.strip():
        out.append(line.rstrip())


def main():
    out = [
        "// Code generated by gen/gen_normalize.py from CPython %s (Unicode %s). DO NOT EDIT."
        % (sys.version.split()[0], unicodedata.unidata_version),
        "",
        "// Port of CPython 3.12's unicodedata (PSF License Version 2;",
        "// Copyright (c) 2001-2024 Python Software Foundation).",
        "",
        "package pyuni",
        "",
    ]
    decomp = {}
    for c in ALL:
        if c in HANGUL:
            continue
        d = unicodedata.normalize("NFKD", chr(c))
        if d != chr(c):
            decomp[c] = d
    out.append("// compatDecompositions holds the full compatibility decomposition (NFKD) of every")
    out.append("// character that has one, the Hangul syllables excepted.")
    out.append("var compatDecompositions = map[rune]string{")
    emit_items(out, ["0x%x: %s," % (c, go_string(decomp[c])) for c in sorted(decomp)])
    out.append("}")
    out.append("")
    runs = []
    for c in ALL:
        k = unicodedata.combining(chr(c))
        if not k:
            continue
        if runs and runs[-1][1] == c - 1 and runs[-1][2] == k:
            runs[-1][1] = c
        else:
            runs.append([c, c, k])
    out.append("// combiningClasses holds the canonical combining classes other than 0.")
    out.append("var combiningClasses = []combiningRun{")
    emit_items(out, ["{0x%x, 0x%x, %d}," % tuple(r) for r in runs])
    out.append("}")
    out.append("")
    pairs = {}
    for c in ALL:
        if c in HANGUL:
            continue
        d = unicodedata.decomposition(chr(c)).split()
        if len(d) == 2 and not d[0].startswith("<"):
            a, b = int(d[0], 16), int(d[1], 16)
            if unicodedata.normalize("NFC", chr(a) + chr(b)) == chr(c):
                pairs[(a, b)] = c
    out.append("// compositions maps the pairs of characters that compose canonically to their primary")
    out.append("// composite, the Hangul syllables excepted.")
    out.append("var compositions = map[[2]rune]rune{")
    emit_items(out, ["{0x%x, 0x%x}: 0x%x," % (a, b, pairs[(a, b)]) for a, b in sorted(pairs)])
    out.append("}")
    with open(sys.argv[1], "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
